#!/usr/bin/env python3
"""Summarise an SvMerge run (wdl/optional/sv_merge.wdl) into docs/results/sv-merge/.

    sv_merge_report.py _runs/sv-merge/_LAST --out docs/results/sv-merge

Writes metrics.json (truvari bench and refine numbers, record counts, task times per strategy),
metrics.md (the same as tables) and counts.tsv.
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path
from typing import Any

PREFIX = "SvMerge."
ORDER = ["pbsv", "sniffles", "union", "collapse", "collapse_loose", "intersect"]
DESCRIPTION = {
    "pbsv": "pbsv alone",
    "sniffles": "Sniffles alone",
    "union": "every call from both, no de-duplication",
    "collapse": "union, near-identical calls merged (`truvari collapse` defaults)",
    "collapse_loose": "union, calls merged at the benchmark's thresholds",
    "intersect": "pbsv calls that Sniffles also made",
}


def label_of(path: str, suffix: str) -> str:
    return Path(path).name.removesuffix(suffix)


def scores(d: dict[str, Any]) -> dict[str, Any]:
    return {
        "tp": d["TP-base"],
        "fn": d["FN"],
        "fp": d["FP"],
        "precision": d["precision"],
        "recall": d["recall"],
        "f1": d["f1"],
    }


def collect(run_dir: Path) -> dict[str, Any]:
    data = json.loads((run_dir / "outputs.json").read_text(encoding="utf-8"))
    outputs = {k.removeprefix(PREFIX): v for k, v in data.get("outputs", data).items()}
    rows: dict[str, dict[str, Any]] = {}
    for path in outputs["summaries"]:
        bench = json.loads(Path(path).read_text(encoding="utf-8"))
        rows.setdefault(label_of(path, ".truvari.json"), {})["bench"] = scores(bench)
    for path in outputs["refine_summaries"]:
        refine = json.loads(Path(path).read_text(encoding="utf-8"))
        rows.setdefault(label_of(path, ".truvari.refine.json"), {})["refine"] = scores(refine)
    for path in outputs["resources"]:
        res = json.loads(Path(path).read_text(encoding="utf-8"))
        rows[res["label"]]["truvari_wall_seconds"] = res["wall_seconds"]
    with open(outputs["counts"], encoding="utf-8", newline="") as fh:
        for rec in csv.DictReader(fh, delimiter="\t"):
            rows[rec["label"]]["records"] = int(rec["records"])
            rows[rec["label"]]["records_ge50"] = int(rec["records_ge50"])
    missing = [k for k in ORDER if not {"bench", "refine", "records"} <= rows.get(k, {}).keys()]
    if missing:
        raise SystemExit(f"error: no results for {', '.join(missing)}")
    # miniwdl writes the inputs it ran with next to outputs.json; inputs left at their default are absent.
    inputs_path = run_dir / "inputs.json"
    inputs = json.loads(inputs_path.read_text(encoding="utf-8")) if inputs_path.is_file() else {}
    return {
        "region": inputs.get(f"{PREFIX}region", "unknown region"),
        "sample": inputs.get(f"{PREFIX}sample", "HG002"),
        "strategies": {k: rows[k] for k in ORDER},
        "counts_tsv": outputs["counts"],
    }


def render(result: dict[str, Any]) -> str:
    s = result["strategies"]
    lines = [
        "# SV merging: benchmark results",
        "",
        f"Generated by `scripts/sv_merge_report.py` from `make sv-merge`. {result['sample']} PacBio HiFi over",
        f"`{result['region']}` against GIAB v5.0q (draft), PASS calls only, with the same truvari",
        "bench and refine settings as the long-read module.",
        "",
        "| Strategy | What it is | Records (50 bp or more) |",
        "|---|---|---:|",
    ]
    for k, row in s.items():
        lines.append(f"| {k} | {DESCRIPTION[k]} | {row['records']:,} ({row['records_ge50']:,}) |")
    for stage, title in (("refine", "After `truvari refine`"), ("bench", "`truvari bench` alone")):
        lines += [
            "",
            f"## {title}",
            "",
            "| Strategy | Found (TP) | Missed (FN) | False (FP) | Precision | Recall | F1 |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for k, row in s.items():
            m = row[stage]
            rates = " | ".join(f"{m[x]:.3f}" for x in ("precision", "recall", "f1"))
            lines.append(f"| {k} | {m['tp']} | {m['fn']} | {m['fp']} | {rates} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_dir", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    result = collect(args.run_dir)
    args.out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(result.pop("counts_tsv"), args.out / "counts.tsv")
    (args.out / "metrics.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    (args.out / "metrics.md").write_text(render(result), encoding="utf-8")


if __name__ == "__main__":
    main()
